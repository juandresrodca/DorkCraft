/**
 * DorkCraft: saved search history
 * -------------------------------
 * Entries live in localStorage and never leave the browser. A search is only
 * stored when the user presses "Save to history".
 */

import { assessDork, LEVEL_LABEL, type Level } from './effectiveness';

export interface HistoryEntry {
  /** When the search was saved, in epoch milliseconds. */
  ts: number;
  query: string;
  dork: string;
  score: number;
  level: Level;
}

export const HISTORY_KEY = 'dc_history';
export const MAX_HISTORY = 50;

type Store = Pick<Storage, 'getItem' | 'setItem' | 'removeItem'>;

const pad = (n: number): string => String(n).padStart(2, '0');

/** Local date and time as YYYY-MM-DD HH:MM. */
export function formatTimestamp(ts: number): string {
  const d = new Date(ts);
  return (
    d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate()) +
    ' ' + pad(d.getHours()) + ':' + pad(d.getMinutes())
  );
}

export function loadHistory(store: Store): HistoryEntry[] {
  let raw: unknown;
  try {
    raw = JSON.parse(store.getItem(HISTORY_KEY) ?? '[]');
  } catch {
    return [];
  }
  if (!Array.isArray(raw)) return [];

  return raw
    .filter((e) => e && typeof e.query === 'string' && typeof e.dork === 'string')
    .map((e) => {
      // Entries saved before scores existed carry only query, dork and ts.
      const scored = typeof e.score === 'number' && e.level in LEVEL_LABEL;
      const fallback = scored ? null : assessDork(e.query, e.dork);
      return {
        ts: typeof e.ts === 'number' ? e.ts : Date.now(),
        query: e.query,
        dork: e.dork,
        score: fallback ? fallback.score : e.score,
        level: fallback ? fallback.level : e.level,
      };
    });
}

/** Adds an entry at the top. Saving the same query and dork again moves it up. */
export function saveEntry(store: Store, entry: HistoryEntry): HistoryEntry[] {
  const rest = loadHistory(store).filter(
    (e) => !(e.query === entry.query && e.dork === entry.dork),
  );
  const next = [entry, ...rest].slice(0, MAX_HISTORY);
  store.setItem(HISTORY_KEY, JSON.stringify(next));
  return next;
}

export function clearHistory(store: Store): void {
  store.removeItem(HISTORY_KEY);
}

/** A code fence longer than any run of backticks inside the dork. */
function fenceFor(text: string): string {
  const longest = (text.match(/`+/g) ?? []).reduce((max, run) => Math.max(max, run.length), 0);
  return '`'.repeat(Math.max(3, longest + 1));
}

/** The history as a Markdown document, newest search first. */
export function buildMarkdown(entries: HistoryEntry[], now: number = Date.now()): string {
  const lines: string[] = [
    '# DorkCraft search history',
    '',
    'Exported ' + formatTimestamp(now) + '. ' + entries.length + ' ' +
      (entries.length === 1 ? 'search' : 'searches') + ', newest first.',
    '',
  ];

  for (const entry of entries) {
    const fence = fenceFor(entry.dork);
    lines.push(
      '## ' + formatTimestamp(entry.ts),
      '',
      '**Query:** ' + entry.query.replace(/\s+/g, ' ').trim(),
      '',
      '**Dork:**',
      '',
      fence,
      entry.dork,
      fence,
      '',
      '**Success score:** ' + entry.score + '/100 (' + LEVEL_LABEL[entry.level] + ')',
      '',
    );
  }

  lines.push(
    '---',
    '',
    'The success score is an estimate of how well each dork is built: its operators, its phrases and',
    'whether it kept the terms of the request. DorkCraft never runs the search, so it is not a count',
    'of Google results.',
    '',
    '*Generated by [DorkCraft](https://github.com/juandresrodca/DorkCraft)*',
    '',
  );
  return lines.join('\n');
}
